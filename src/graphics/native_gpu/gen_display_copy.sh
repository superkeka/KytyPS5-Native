#!/bin/sh
# Regenerates displayCopyShader.inc from displayCopy.s. Needs llvm-mc and llvm-objcopy (LLVM 17+).
set -e
cd "$(dirname "$0")"
LLVM_BIN=${LLVM_BIN:-/opt/homebrew/opt/llvm/bin}
TMP=$(mktemp -d)
OUT=displayCopyShader.inc
"$LLVM_BIN/llvm-mc" -triple=amdgcn -mcpu=gfx1013 -mattr=+wavefrontsize64 -filetype=obj displayCopy.s -o "$TMP/copy.o"
"$LLVM_BIN/llvm-objcopy" -O binary --only-section=.text "$TMP/copy.o" "$TMP/copy.bin"
{
	echo "// Generated by gen_display_copy.sh from displayCopy.s (gfx1013, wave64). Do not edit."
	echo "static constexpr uint32_t kDisplayCopyShader[] = {"
	od -An -v -tx4 "$TMP/copy.bin" | tr -s ' \n' '\n\n' | sed '/^$/d;s/^/0x/;s/$/u,/' | paste -sd ' ' - | fold -s -w 110 | sed 's/^/\t/;s/ *$//'
	echo "};"
} > "$OUT"
rm -f "$TMP/copy.o" "$TMP/copy.bin"
rmdir "$TMP"
